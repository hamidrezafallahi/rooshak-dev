    /// <summary>Label of a table, entity or controller name; the name itself when it has none.</summary>
    public static string Entity(string? name)
    {
        if (string.IsNullOrWhiteSpace(name))
            return "رکورد";

        return Entities.TryGetValue(name.Trim(), out var label) ? label : name.Trim();
    }

    /// <summary>
    /// Label of a field. Accepts the forms the framework reports a field in:
    /// "persianName", "PersianName", "$.items[0].price" or "command.Price".
    /// </summary>
    public static string Field(string? name)
    {
        var key = LastSegment(name);
        if (key.Length == 0)
            return "مقدار ارسال‌شده";

        return Fields.TryGetValue(key, out var label) ? label : key;
    }

    /// <summary>"$.items[0].price" → "price", the name a form field goes by.</summary>
    public static string LastSegment(string? name)
    {
        if (string.IsNullOrWhiteSpace(name))
            return string.Empty;

        var key = name.Trim();
        if (key.StartsWith('$'))
            key = key[1..];

        var bracket = key.LastIndexOf('[');
        if (bracket >= 0 && key.EndsWith(']'))
            key = key[..bracket];

        var dot = key.LastIndexOf('.');
        return dot >= 0 ? key[(dot + 1)..] : key;
    }
